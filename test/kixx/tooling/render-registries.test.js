    describe('the routes registry', ({ it }) => {
        it('lists core\'s routes first, then each plugin\'s in order', () => {
            const core = makeBareCore({ routes: [ { module: './http-router/core-routes.js' } ] });
            const text = render(resolveInstallation({ core, plugins: [ makeVisits(), makeAdmin() ] }))
                .get(ROUTES_REGISTRY_FILE_NAME);

            assertEqual(
                [
                    '    ...mountRoutes({ plugin: "kixx", module: "./http-router/core-routes.js", routes: kixxHttpRouterCoreRoutes }),',
                    '    ...mountRoutes({ plugin: "admin", module: "./routes.js", mount: "/admin", name: "admin", routes: adminRoutes }),',
                    '    ...mountRoutes({ plugin: "visits", module: "./routes.js", routes: visitsRoutes }),',
                    '    ...mountRoutes({ plugin: "visits", module: "./admin-routes.js", mount: "/admin/visits", name: "admin-visits", routes: visitsAdminRoutes }),',
                ].join('\n'),
                linesMatching(text, /mountRoutes\(/).join('\n'),
            );

            assert(text.includes('import kixxHttpRouterCoreRoutes from "./kixx/http-router/core-routes.js";'));
        });

        it('leaves out a whenInstalled route when the named plugin is not installed', () => {
            const visits = makeVisits({ dependencies: [] });
            const text = render(resolveInstallation({ core: makeBareCore(), plugins: [ visits ] }))
                .get(ROUTES_REGISTRY_FILE_NAME);

            assertEqual(1, linesMatching(text, /mountRoutes\(\{/).length);
            assertFalsy(text.includes('admin-routes.js'));
        });

        it('imports a module once when it is mounted twice', () => {
            const plugin = makePlugin('visits', {
                routes: [
                    { module: './routes.js', mount: '/visits', name: 'visits' },
                    { module: './routes.js', mount: '/v', name: 'v' },
                ],
            });
            const text = render(resolveInstallation({ core: makeBareCore(), plugins: [ plugin ] }))
                .get(ROUTES_REGISTRY_FILE_NAME);

            assertEqual(1, linesMatching(text, /^import visitsRoutes from /).length);
            assertEqual(2, linesMatching(text, /routes: visitsRoutes \}\),$/).length);
        });

        it('never takes a name the registry declares itself', () => {
            const plugin = makePlugin('plugin', { routes: [ { module: './routes.js' } ] });
            const text = render(resolveInstallation({ core: makeBareCore(), plugins: [ plugin ] }))
                .get(ROUTES_REGISTRY_FILE_NAME);

            assert(text.includes('import pluginRoutes2 from "./plugins/plugin/routes.js";'));
        });

        it('exports an empty array and imports nothing when there is no route', () => {
            const text = render(resolveInstallation({ core: makeBareCore(), plugins: [] }))
                .get(ROUTES_REGISTRY_FILE_NAME);

            assertEqual(toText([
                ...HEADER,
                '',
                '// Every route the installed plugins contribute, in order. Spread it into a',
                '// virtual host\'s routes, before the catch-all.',
                'export const pluginRoutes = [];',
            ]), text);
        });
    });

    describe('the coreDirectory option', ({ it }) => {
        function specifiers(text) {
            return Array.from(text.matchAll(/ from ("[^"]+");$/gm)).map((match) => JSON.parse(match[1]));
        }

        it('defaults to kixx', () => {
            const files = render(makeInstallation());

            for (const name of JAVASCRIPT_FILE_NAMES) {
                const core = specifiers(files.get(name)).filter((specifier) => !specifier.startsWith('./plugins/'));

                assert(core.length > 0, name);
                assert(core.every((specifier) => specifier.startsWith('./kixx/')), name);
            }
        });

        it('reaches a core outside the project', () => {
            const files = render(makeInstallation(), { coreDirectory: '../../../kixx' });

            for (const name of JAVASCRIPT_FILE_NAMES) {
                const core = specifiers(files.get(name)).filter((specifier) => !specifier.startsWith('./plugins/'));

                assert(core.length > 0, name);
                assert(core.every((specifier) => specifier.startsWith('../../../kixx/')), name);
            }

            assert(files.get(ROUTES_REGISTRY_FILE_NAME).includes(
                'import { mountRoutes } from "../../../kixx/http-router/mount-routes.js";',
            ));
        });

        it('rejects a path that is not a safe relative POSIX path', () => {
            const installation = makeInstallation();

            for (const coreDirectory of [ '', '/kixx', 'kixx/', 'kixx//lib', 'kixx\\lib', 'ki"xx', 'ki xx', 7, null ]) {
                const caught = catchError(() => render(installation, { coreDirectory }));

                assert(caught, `expected ${ JSON.stringify(coreDirectory) } to be rejected`);
                assertEqual('AssertionError', caught.name);
                assertMatches('options.coreDirectory must be a relative POSIX path', caught.message);
            }
        });
    });

    describe('the secrets manifest', ({ it }) => {
        it('parses to the secrets value both registries hold', () => {
            const files = render(makeInstallation());
            const parsed = parseSecretsManifest(files.get(SECRETS_MANIFEST_FILE_NAME));

            assertEqual('VISITS_SIGNING_SECRET', parsed.required.join(','));
            assertEqual('SUPPORT_TOKEN,VISITS_DEBUG_TOKEN', parsed.optional.join(','));
            assertEqual('DEPLOY_KEY_HASH', parsed.requiredOutsideDevelopment.join(','));

            for (const name of [ NODE_REGISTRY_FILE_NAME, CLOUDFLARE_REGISTRY_FILE_NAME ]) {
                assertEqual(JSON.stringify(parsed), JSON.stringify(readDataExport(files.get(name), 'secrets')), name);
            }
        });

        it('is the header alone, and parses to three empty lists, when no secret is declared', () => {
            const files = render(resolveInstallation({ core: makeBareCore(), plugins: [] }));
            const text = files.get(SECRETS_MANIFEST_FILE_NAME);

            assertEqual(toText(SECRETS_HEADER), text);
            assertEqual(
                '{"required":[],"optional":[],"requiredOutsideDevelopment":[]}',
                JSON.stringify(parseSecretsManifest(text)),
            );
            assertEqual(
                '{"required":[],"optional":[],"requiredOutsideDevelopment":[]}',
                JSON.stringify(readDataExport(files.get(NODE_REGISTRY_FILE_NAME), 'secrets')),
            );
        });

        it('holds no header line that reads as a directive', () => {
            const text = render(resolveInstallation({ core: makeBareCore(), plugins: [] }))
                .get(SECRETS_MANIFEST_FILE_NAME);

            const directives = [ '# @optional', '# @required-outside-development' ];

            assertEqual(0, text.split('\n').filter((line) => directives.includes(line.trim())).length);
        });
    });
