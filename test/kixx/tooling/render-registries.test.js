function makeCore(overrides) {
    const manifest = Object.assign({
        name: 'kixx',
        version: '7.0.0-alpha.0',
        description: 'Kixx core.',
        services: [ 'KeyValueStore' ],
        lifecycle: [ './hyperview/plugin.js' ],
        adapters: {
            node: {
                lifecycle: [ './adapters/node/key-value-store/plugin.js' ],
                loggerWriter: './adapters/node/logger-writer/lib/logger-writer.js',
                serverRequest: './adapters/node/server-request/lib/server-request.js',
            },
            cloudflare: {
                lifecycle: [ './adapters/cloudflare/key-value-store/plugin.js' ],
                loggerWriter: './adapters/cloudflare/logger-writer/lib/logger-writer.js',
                serverRequest: './adapters/cloudflare/server-request/lib/server-request.js',
            },
        },
        config: {
            keys: [ 'CONTENT_STORE', 'HYPERVIEW', 'KEY_VALUE_STORE' ],
            defaults: {
                all: { HYPERVIEW: { useTemplateCache: false } },
                cloudflare: {
                    KEY_VALUE_STORE: { bindingName: 'KEY_VALUE_STORE' },
                    CONTENT_STORE: { durableObject: { bindingName: 'CA_STORE_DURABLE_OBJECT' } },
                },
            },
        },
        secrets: [ { name: 'DEPLOY_KEY_HASH', required: 'outsideDevelopment', description: 'Hash of the deploy key.' } ],
        templateHelpers: [ 'if', 'each', 'formatDate' ],
        cloudflare: {
            kvNamespaces: [ { config: 'KEY_VALUE_STORE' } ],
            durableObjects: [
                {
                    className: 'ContentAddressableIndexStore',
                    module: './adapters/cloudflare/content-store/lib/content-addressable-index-store.js',
                    config: 'CONTENT_STORE.durableObject',
                },
            ],
        },
    }, overrides);

    return validatePluginManifest(manifest, { file: 'kixx/plugin.json', isCore: true });
}

// A core that contributes nothing but what every core manifest must hold.
function makeBareCore(overrides) {
    return makeCore(Object.assign({
        config: {},
        secrets: [],
        cloudflare: {},
        templateHelpers: [],
    }, overrides));
}

function makePlugin(name, overrides) {
    const manifest = Object.assign({
        name,
        version: '7.0.0',
        core: '7.0.0',
        description: `The ${ name } plugin.`,
    }, overrides);

    return validatePluginManifest(manifest, { file: `plugins/${ name }/plugin.json`, directoryName: name });
}

function makeAdmin() {
    return makePlugin('admin', {
        lifecycle: [ './plugin.js' ],
        routes: [ { module: './routes.js', mount: '/admin', name: 'admin' } ],
    });
}

// A plugin that uses every part of a manifest the renderers read.
function makeVisits(overrides) {
    return makePlugin('visits', Object.assign({
        dependencies: [ 'admin' ],
        lifecycle: [ './plugin.js' ],
        adapters: {
            node: { lifecycle: [ './adapters/node/plugin.js' ] },
            cloudflare: { lifecycle: [ './adapters/cloudflare/plugin.js' ] },
        },
        config: {
            keys: [ 'VISITS' ],
            defaults: {
                all: { VISITS: { greeting: 'hello' } },
                node: { VISITS: { store: 'sqlite' } },
                cloudflare: { VISITS: { durableObject: { bindingName: 'VISITS_DURABLE_OBJECT' } } },
            },
        },
        secrets: [
            { name: 'VISITS_SIGNING_SECRET', description: 'Signs visit tokens.' },
            { name: 'VISITS_DEBUG_TOKEN', required: false, description: 'Unlocks debug output.' },
        ],
        cloudflare: {
            durableObjects: [
                { className: 'VisitsStore', module: './adapters/cloudflare/lib/visits-store.js', config: 'VISITS.durableObject' },
            ],
        },
        routes: [ { module: './routes.js' } ],
        content: { pagesDirectory: './pages', staticAssetsDirectory: './static-assets' },
        templateHelpers: [ 'visitCount', 'Ordinal' ],
        whenInstalled: {
            admin: {
                routes: [ { module: './admin-routes.js', mount: '/admin/visits', name: 'admin-visits' } ],
            },
        },
    }, overrides));
}

function makeApp() {
    return validateAppManifest({
        secrets: [ { name: 'SUPPORT_TOKEN', required: false, description: 'Lets support staff sign in.' } ],
        templateHelpers: [ 'initials', 'formatDate' ],
    }, { file: 'app/app.json' });
}

// Core and two plugins: the model the whole-text assertions render.
function makeInstallation() {
    return resolveInstallation({ core: makeCore(), plugins: [ makeVisits(), makeAdmin() ], app: makeApp() });
}

function render(installation, options) {
    return renderRegistryFiles(installation, options);
}

function toText(lines) {
    return `${ lines.join('\n') }\n`;
}

function catchError(fn) {
    try {
        fn();
    } catch (error) {
        return error;
    }
    return null;
}

// Reads the value a generated registry assigns to one of its data exports.
function readDataExport(text, name) {
    const start = text.indexOf(`export const ${ name } = `);
    assert(start >= 0, `expected an export named ${ name }`);

    const valueStart = start + `export const ${ name } = `.length;
    const valueEnd = text.indexOf(';\n', valueStart);

    return JSON.parse(text.slice(valueStart, valueEnd));
}

function exportNames(text) {
    const names = [];

    for (const match of text.matchAll(/^export const (\w+)/gm)) {
        names.push(match[1]);
    }

    for (const match of text.matchAll(/^export \{ ([^}]+) \};$/gm)) {
        names.push(...match[1].split(', '));
    }

    return names.sort().join(',');
}

function linesMatching(text, pattern) {
    return text.split('\n').filter((line) => pattern.test(line));
}


