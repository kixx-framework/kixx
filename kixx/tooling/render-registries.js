import { assert, isPlainObject, isString, isUndefined } from '../assertions/mod.js';


export const NODE_REGISTRY_FILE_NAME = 'node-registry.generated.js';
export const CLOUDFLARE_REGISTRY_FILE_NAME = 'cloudflare-registry.generated.js';
export const DURABLE_OBJECT_REGISTRY_FILE_NAME = 'cloudflare-durable-objects.generated.js';
export const ROUTES_REGISTRY_FILE_NAME = 'routes.generated.js';
export const SECRETS_MANIFEST_FILE_NAME = 'example.env.secrets';

const DEFAULT_CORE_DIRECTORY = 'kixx';

// A POSIX path relative to the project root. It is written into import
// specifiers, so each segment holds only characters that are safe there.
const CORE_DIRECTORY_PATTERN = /^[A-Za-z0-9_.-]+(?:\/[A-Za-z0-9_.-]+)*$/;

// The one manifest value written into source as a bare identifier.
const CLASS_NAME_PATTERN = /^[A-Z][A-Za-z0-9_]*$/;

const CORE_OWNER = 'kixx';
const APP_OWNER = 'app';

const CONTENT_DIRECTORY_KEYS = [ 'pagesDirectory', 'templatesDirectory', 'staticAssetsDirectory' ];

const HEADER_LINES = [
    'Generated by Kixx from the installed plugin manifests. Do not edit.',
    'Regenerate it after a manifest changes.',
];

// The second line switches the linter off for the whole file, so a project's
// lint config needs no entry for generated files.
const JAVASCRIPT_HEADER = [
    ...HEADER_LINES.map((line) => `// ${ line }`),
    '/* eslint-disable */',
];

const SECRETS_HEADER = [
    ...HEADER_LINES,
    '',
    'This file is the template for .env.<environment>.secrets, and the list of',
    'secret names every deployment must provide. Only the names are read: each',
    'value is a placeholder.',
].map((line) => `# ${ line }`.trimEnd());

// The names each generated module declares itself. No import may take one.
const REGISTRY_NAMES = [ 'LoggerWriter', 'ServerRequest', 'plugins', 'configDefaults', 'secrets', 'contentRoots' ];
const ROUTES_NAMES = [ 'mountRoutes', 'pluginRoutes' ];


/**
 * @typedef {import('./resolve-installation.js').Installation} Installation
 */


/**
 * Reads the `coreDirectory` option: where core lives, as a POSIX path relative
 * to the project root. It may begin with `../`.
 * @param {Object} [options]
 * @param {string} [options.coreDirectory='kixx']
 * @returns {string} The checked path
 * @throws {AssertionError} When the path is absolute, empty, or holds a character an import specifier can't safely carry
 */
export function readCoreDirectoryOption(options) {
    const { coreDirectory = DEFAULT_CORE_DIRECTORY } = options ?? {};

    assert(
        isString(coreDirectory) && CORE_DIRECTORY_PATTERN.test(coreDirectory),
        'options.coreDirectory must be a relative POSIX path with segments of letters, digits, ".", "_", and "-"',
    );

    return coreDirectory;
}

/**
 * Renders the text of the five files generated from a resolved installation:
 * a registry module for each target, the Durable Object registry, the routes
 * registry, and the secrets manifest.
 *
 * It is pure, and its output is deterministic: the same installation gives the
 * same text, with LF line endings and one trailing newline. Every manifest
 * string that reaches a JavaScript file is written with JSON.stringify.
 *
 * @param {Installation} installation - The model resolveInstallation() returned
 * @param {Object} [options]
 * @param {string} [options.coreDirectory='kixx'] - Where core lives, as a POSIX path relative to the project root
 * @returns {Map<string, string>} File text by file name, always the same five names in the same order
 * @throws {AssertionError} When `coreDirectory` is not a safe relative path
 */
export function renderRegistryFiles(installation, options) {
    assert(isPlainObject(installation), 'renderRegistryFiles: installation must be a resolved installation');

    const coreDirectory = readCoreDirectoryOption(options);

    // Turns a path its manifest wrote, relative to the owner's directory,
    // into a path from the project root.
    const toProjectPath = (owner, path) => {
        const directory = owner === CORE_OWNER ? coreDirectory : `plugins/${ owner }`;
        return `${ directory }/${ path.slice(2) }`;
    };

    const model = { installation, toProjectPath };

    return new Map([
        [ NODE_REGISTRY_FILE_NAME, renderTargetRegistry(model, 'node') ],
        [ CLOUDFLARE_REGISTRY_FILE_NAME, renderTargetRegistry(model, 'cloudflare') ],
        [ DURABLE_OBJECT_REGISTRY_FILE_NAME, renderDurableObjectRegistry(model) ],
        [ ROUTES_REGISTRY_FILE_NAME, renderRoutesRegistry(model) ],
        [ SECRETS_MANIFEST_FILE_NAME, renderSecretsManifest(installation) ],
    ]);
}

function renderTargetRegistry(model, target) {
    const { installation, toProjectPath } = model;
    const { lifecycle, loggerWriter, serverRequest, configDefaults } = installation.targets[target];

    const modules = nameModules(lifecycle, REGISTRY_NAMES);

    const imports = [
        `import LoggerWriter from ${ quoteSpecifier(toProjectPath(CORE_OWNER, loggerWriter)) };`,
        `import ServerRequest from ${ quoteSpecifier(toProjectPath(CORE_OWNER, serverRequest)) };`,
    ];

    const entries = [];

    for (const { owner, module, identifier } of modules.values()) {
        imports.push(`import * as ${ identifier } from ${ quoteSpecifier(toProjectPath(owner, module)) };`);
        entries.push(`    [ ${ JSON.stringify(`${ owner }:${ module }`) }, ${ identifier } ],`);
    }

    const contentRoots = installation.contentRoots.map((root) => {
        const record = { plugin: root.owner };

        for (const key of CONTENT_DIRECTORY_KEYS) {
            if (!isUndefined(root[key])) {
                record[key] = toProjectPath(root.owner, root[key]);
            }
        }

        return record;
    });

    return joinLines([
        ...JAVASCRIPT_HEADER,
        '',
        ...imports,
        '',
        'export { LoggerWriter, ServerRequest };',
        '',
        '// Lifecycle modules, in the order they run.',
        ...wrapLines('export const plugins = new Map([', entries, ']);'),
        '',
        '// Config defaults for this target; the project\'s config is merged over them.',
        `export const configDefaults = ${ JSON.stringify(configDefaults, null, 4) };`,
        '',
        '// Every secret the installed code declares.',
        `export const secrets = ${ JSON.stringify(listSecretNames(installation.secrets), null, 4) };`,
        '',
        '// Where plugin content lives, as paths from the project root.',
        `export const contentRoots = ${ JSON.stringify(contentRoots, null, 4) };`,
    ]);
}

// Durable Object classes have a file of their own because the Cloudflare
// entry point re-exports all of it, and because it alone imports the shells,
// which only Cloudflare can load.
function renderDurableObjectRegistry(model) {
    const { installation, toProjectPath } = model;

    const exports = installation.durableObjects.map(({ owner, className, module }) => {
        assert(
            CLASS_NAME_PATTERN.test(className),
            `renderRegistryFiles: Durable Object class name "${ className }" is not a class identifier`,
        );

        return `export { default as ${ className } } from ${ quoteSpecifier(toProjectPath(owner, module)) };`;
    });

    return joinLines([
        ...JAVASCRIPT_HEADER,
        '',
        // A module with no import or export would not read as a module.
        ...(exports.length > 0 ? exports : [ 'export {};' ]),
    ]);
}

function renderRoutesRegistry(model) {
    const { installation, toProjectPath } = model;
    const { routes } = installation;

    const modules = nameModules(routes, ROUTES_NAMES);
    const imports = [];

    if (routes.length > 0) {
        imports.push(
            `import { mountRoutes } from ${ quoteSpecifier(toProjectPath(CORE_OWNER, './http-router/mount-routes.js')) };`,
        );
    }

    for (const { owner, module, identifier } of modules.values()) {
        imports.push(`import ${ identifier } from ${ quoteSpecifier(toProjectPath(owner, module)) };`);
    }

    const calls = routes.map((route) => {
        const { identifier } = modules.get(toModuleKey(route));

        const args = [
            `plugin: ${ JSON.stringify(route.owner) }`,
            `module: ${ JSON.stringify(route.module) }`,
        ];

        if (!isUndefined(route.mount)) {
            args.push(`mount: ${ JSON.stringify(route.mount) }`, `name: ${ JSON.stringify(route.name) }`);
        }

        args.push(`routes: ${ identifier }`);

        return `    ...mountRoutes({ ${ args.join(', ') } }),`;
    });

    return joinLines([
        ...JAVASCRIPT_HEADER,
        '',
        ...(imports.length > 0 ? [ ...imports, '' ] : []),
        '// Every route the installed plugins contribute, in order. Spread it into a',
        '// virtual host\'s routes, before the catch-all.',
        ...wrapLines('export const pluginRoutes = [', calls, '];'),
    ]);
}

// Keeps the grammar parseSecretsManifest() reads: a comment line that is
// exactly `# @optional` or `# @required-outside-development` marks the next
// entry, with only comment lines between.
function renderSecretsManifest(installation) {
    const blocks = installation.secrets.map((secret) => {
        const lines = [];

        if (secret.required === false) {
            lines.push('# @optional');
        } else if (secret.required === 'outsideDevelopment') {
            lines.push('# @required-outside-development');
        }

        lines.push(
            `# Declared by ${ describeOwner(secret.owner) }.`,
            `# ${ secret.description }`,
            // Only the name is read. The value is a placeholder to replace.
            `${ secret.name }=replace-me`,
        );

        return lines.join('\n');
    });

    return `${ [ SECRETS_HEADER.join('\n'), ...blocks ].join('\n\n') }\n`;
}

function describeOwner(owner) {
    if (owner === CORE_OWNER) {
        return 'Kixx core';
    }

    return owner === APP_OWNER ? 'the app' : `plugin ${ owner }`;
}

// The shape parseSecretsManifest() returns, so boot checks the same lists a
// deployment tool reads from the secrets manifest.
function listSecretNames(secrets) {
    const namesWhere = (required) => {
        return secrets.filter((secret) => secret.required === required).map((secret) => secret.name).sort();
    };

    return {
        required: namesWhere(true),
        optional: namesWhere(false),
        requiredOutsideDevelopment: namesWhere('outsideDevelopment'),
    };
}

// Gives every distinct module one import identifier, in the order of first
// use. A module used twice is imported once.
function nameModules(records, reservedNames) {
    const modules = new Map();
    const taken = new Set(reservedNames);

    for (const record of records) {
        const key = toModuleKey(record);

        if (modules.has(key)) {
            continue;
        }

        const base = toIdentifier(record.owner, record.module);
        let identifier = base;

        for (let suffix = 2; taken.has(identifier); suffix += 1) {
            identifier = `${ base }${ suffix }`;
        }

        taken.add(identifier);
        modules.set(key, { owner: record.owner, module: record.module, identifier });
    }

    return modules;
}

function toModuleKey(record) {
    return `${ record.owner }:${ record.module }`;
}

// Camel case of the owner and the module path. Deriving the identifier from
// the path, not from a counter, keeps a diff small when a plugin is added.
function toIdentifier(owner, module) {
    const path = module.slice(2, -3);
    const words = `${ owner }/${ path }`.split(/[^A-Za-z0-9]+/).filter((word) => word !== '');

    // A file name with no letter or digit adds no word, and the owner's name
    // alone could be a reserved word. An identifier of two words or more
    // holds a capital letter or a digit, so it never is one.
    if (words.length === 1) {
        words.push('module');
    }

    return words.map((word, index) => {
        return index === 0 ? word : word[0].toUpperCase() + word.slice(1);
    }).join('');
}

function quoteSpecifier(projectPath) {
    const specifier = /^\.\.?\//.test(projectPath) ? projectPath : `./${ projectPath }`;
    return JSON.stringify(specifier);
}

// An empty list is written on one line.
function wrapLines(open, lines, close) {
    return lines.length > 0 ? [ open, ...lines, close ] : [ `${ open }${ close }` ];
}

function joinLines(lines) {
    return `${ lines.join('\n') }\n`;
}
